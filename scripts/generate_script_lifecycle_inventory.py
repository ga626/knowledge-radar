from __future__ import annotations

import argparse
from datetime import datetime, timezone
import json
import os
from pathlib import Path
import re
from typing import Any


ROOT = Path(__file__).resolve().parents[1]
MANIFEST = ROOT / "config" / "project-structure.manifest.json"
OUTPUT_JSON = ROOT / "docs" / "script-lifecycle-inventory.json"
OUTPUT_MD = ROOT / "docs" / "脚本生命周期清单.md"
SCHEMA = "knowledgeradar-script-lifecycle-inventory/v1"
GENERATED = "This file is generated by scripts/generate_script_lifecycle_inventory.py."

SCRIPT_PATTERNS = [
    "scripts/*.py",
    "scripts/*.ps1",
    "scripts/*.bat",
    "scripts/*.cmd",
    ".codex/hooks/*.py",
    ".githooks/*",
    "tools/**/*.py",
    "tools/**/*.ps1",
    "tools/**/*.bat",
    "tools/**/*.cmd",
]


def _rel(path: Path) -> str:
    return path.relative_to(ROOT).as_posix()


def _load_manifest() -> dict[str, Any]:
    return json.loads(MANIFEST.read_text(encoding="utf-8-sig"))


def _discover_files() -> list[Path]:
    files: set[Path] = set()
    for pattern in SCRIPT_PATTERNS:
        files.update(path for path in ROOT.glob(pattern) if path.is_file())
    return sorted(files)


def _repo_text_files() -> list[Path]:
    roots = ["AGENTS.md", "STRUCTURE.md", ".codex", ".githooks", "config", "scripts", "tests", "docs"]
    result: list[Path] = []
    for root in roots:
        path = ROOT / root
        if path.is_file():
            result.append(path)
        elif path.is_dir():
            for directory, children, files in os.walk(path):
                children[:] = [name for name in children if name not in {"worktrees", "public-repos", "preview-state", ".git", "node_modules", "__pycache__", "dist", "release", ".python312"}]
                for name in files:
                    item = Path(directory) / name
                    if item.suffix.lower() in {".py", ".json", ".md", ".ps1", ".bat", ".cmd", ""} and item not in {OUTPUT_JSON, OUTPUT_MD}:
                        result.append(item)
    return result


def _reference_counts(paths: list[Path]) -> dict[str, int]:
    counts: dict[str, int] = {}
    text_files = _repo_text_files()
    texts = []
    for text_file in text_files:
        try:
            texts.append(text_file.read_text(encoding="utf-8-sig", errors="replace"))
        except OSError:
            continue
    for script in paths:
        rel = _rel(script)
        stem = script.stem
        needle_variants = {rel, rel.replace("/", "\\"), script.name}
        if script.suffix == ".py":
            needle_variants.add(rel[:-3].replace("/", "."))
            needle_variants.add(stem)
        elif len(stem) >= 8:
            needle_variants.add(stem)
        count = 0
        for text in texts:
            for needle in needle_variants:
                if "/" in needle or "\\" in needle or "." in needle or "-" in needle:
                    count += len(re.findall(re.escape(needle), text))
                else:
                    count += len(re.findall(rf"\b{re.escape(needle)}\b", text))
        counts[rel] = count
    return counts


def _classify(path: str, manifest: dict[str, Any], ref_count: int) -> tuple[str, str]:
    watch_paths = set(str(item).replace("\\", "/") for item in manifest.get("watch_paths", []))
    watch_globs = [str(item).replace("\\", "/") for item in manifest.get("watch_path_globs", [])]
    if path in {".codex/hooks/quality_gate_hook.py", ".githooks/pre-commit", ".githooks/pre-push", "scripts/kr_quality_gate.py"}:
        return "S0", "hook_or_quality_gate_bootstrap"
    if path in watch_paths:
        return "S1", "manifest_watch_path"
    if any(Path(path).match(pattern) for pattern in watch_globs):
        return "S1", "manifest_watch_glob"
    if path.startswith("scripts/verify_") or path.startswith("scripts/check_") or path.startswith("scripts/generate_"):
        return "S1", "official_verification_or_generation"
    if path.startswith("tools/"):
        return ("S2", "reusable_tool") if ref_count else ("S3", "tool_spike_or_manual_utility")
    return ("S2", "referenced_reusable_script") if ref_count else ("S3", "unreferenced_candidate")


def build_inventory() -> dict[str, Any]:
    manifest = _load_manifest()
    files = _discover_files()
    refs = _reference_counts(files)
    entries: list[dict[str, Any]] = []
    for path in files:
        rel = _rel(path)
        level, reason = _classify(rel, manifest, refs.get(rel, 0))
        entries.append(
            {
                "path": rel,
                "level": level,
                "reason": reason,
                "reference_count": refs.get(rel, 0),
                "action": {
                    "S0": "do_not_move_before_dual_track_wrapper_and_full_closeout",
                    "S1": "move_only_with_manifest_and_callsite_updates",
                    "S2": "may_move_after_targeted_checks",
                    "S3": "archive_or_delete_only_after_owner_review",
                    "S4": "runtime_artifact_not_source",
                }[level],
            }
        )
    return {
        "schema": SCHEMA,
        "generated_at": datetime.fromtimestamp(
            max([path.stat().st_mtime for path in files] + [MANIFEST.stat().st_mtime]),
            timezone.utc,
        ).isoformat(),
        "generator": "scripts/generate_script_lifecycle_inventory.py",
        "entries": entries,
        "counts": {level: sum(1 for entry in entries if entry["level"] == level) for level in ["S0", "S1", "S2", "S3", "S4"]},
    }


def render_markdown(payload: dict[str, Any]) -> str:
    lines = [
        "# 脚本生命周期清单",
        "",
        GENERATED,
        "",
        f"生成时间：{payload['generated_at']}",
        "",
        "## 等级说明",
        "",
        "| 等级 | 含义 | 处理策略 |",
        "| --- | --- | --- |",
        "| S0 | 自举/门控脚本 | 最后迁移；必须旧路径 wrapper + 新路径实现双轨验证 |",
        "| S1 | 官方验证/生成/被 manifest 监控脚本 | 迁移需同步 manifest、调用方和结构 closeout |",
        "| S2 | 可复用开发工具 | 可小批量迁移，先跑目标测试 |",
        "| S3 | 一次性或低引用工具 | 需 owner review 后归档或删除 |",
        "| S4 | 运行产物 | 不应作为源码脚本管理 |",
        "",
        "## 清单",
        "",
        "| 路径 | 等级 | 原因 | 引用数 | 动作 |",
        "| --- | --- | --- | ---: | --- |",
    ]
    for entry in payload["entries"]:
        lines.append(
            f"| `{entry['path']}` | {entry['level']} | {entry['reason']} | {entry['reference_count']} | {entry['action']} |"
        )
    return "\n".join(lines).rstrip() + "\n"


def write_outputs(payload: dict[str, Any], *, check: bool) -> list[str]:
    outputs = {
        OUTPUT_JSON: json.dumps(payload, ensure_ascii=False, indent=2) + "\n",
        OUTPUT_MD: render_markdown(payload),
    }
    changed: list[str] = []
    for path, text in outputs.items():
        existing = path.read_text(encoding="utf-8") if path.exists() else ""
        if existing != text:
            changed.append(_rel(path))
            if not check:
                path.parent.mkdir(parents=True, exist_ok=True)
                path.write_text(text, encoding="utf-8")
    return changed


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    parser.add_argument("--json", action="store_true")
    args = parser.parse_args(argv)

    payload = build_inventory()
    changed = write_outputs(payload, check=args.check)
    result = {
        "schema": "knowledgeradar-script-lifecycle-generation/v1",
        "status": "PASS" if not changed else ("FAIL" if args.check else "PASS"),
        "changed": changed,
        "counts": payload["counts"],
    }
    if args.json:
        print(json.dumps(result, ensure_ascii=False, indent=2))
    else:
        if changed:
            print("Script lifecycle inventory differs:" if args.check else "Script lifecycle inventory updated:")
            for item in changed:
                print(f"- {item}")
        else:
            print("Script lifecycle inventory is up to date.")
    return 0 if result["status"] == "PASS" else 1


if __name__ == "__main__":
    raise SystemExit(main())
