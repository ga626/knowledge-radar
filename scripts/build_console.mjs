// 使用 Node 内置 TypeScript 擦除器，无运行时依赖；这不替代完整 tsc 类型检查。
import {stripTypeScriptTypes} from 'node:module';
import {readFileSync,writeFileSync} from 'node:fs';
const root=new URL('../src/onboarding/static/',import.meta.url);
for (const name of ['console','research_workspace']) {
  const output=`// Generated by scripts/build_console.mjs. Edit ${name}.ts.\n`+stripTypeScriptTypes(readFileSync(new URL(name+'.ts',root),'utf8'),{mode:'strip'}).split('\n').map(line=>line.trimEnd()).join('\n').trimEnd()+'\n';
  const target=new URL(name+'.js',root);
  if(process.argv.includes('--check')){if(readFileSync(target,'utf8')!==output)throw Error('console_build_drift:'+name);}
  else writeFileSync(target,output);
}
console.log('console TypeScript emitted; runtime dependencies: 0');
