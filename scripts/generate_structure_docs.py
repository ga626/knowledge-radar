from __future__ import annotations

import argparse
import json
from pathlib import Path
from typing import Dict, Iterable, List


ROOT = Path(__file__).resolve().parents[1]
MANIFEST_PATH = ROOT / "config" / "project-structure.manifest.json"


def load_manifest() -> dict:
    with MANIFEST_PATH.open("r", encoding="utf-8") as handle:
        return json.load(handle)


def generated_block(block_id: str, body: str) -> str:
    body = body.strip()
    return (
        f"<!-- KR-GENERATED:{block_id}:START -->\n"
        f"{body}\n"
        f"<!-- KR-GENERATED:{block_id}:END -->"
    )


def replace_block(existing: str, block_id: str, body: str) -> str:
    start = f"<!-- KR-GENERATED:{block_id}:START -->"
    end = f"<!-- KR-GENERATED:{block_id}:END -->"
    block = generated_block(block_id, body)
    if start in existing and end in existing:
        before, rest = existing.split(start, 1)
        _, after = rest.split(end, 1)
        prefix = before.rstrip()
        return (prefix + "\n\n" if prefix else "") + block + "\n" + after.lstrip()
    if existing.strip():
        return existing.rstrip() + "\n\n" + block + "\n"
    return block + "\n"


def table(headers: List[str], rows: Iterable[Iterable[str]]) -> str:
    rendered = [
        "| " + " | ".join(headers) + " |",
        "| " + " | ".join("---" for _ in headers) + " |",
    ]
    for row in rows:
        rendered.append("| " + " | ".join(str(cell).replace("\n", " ") for cell in row) + " |")
    return "\n".join(rendered)


def bullet_list(items: Iterable[str]) -> str:
    return "\n".join(f"- {item}" for item in items)


def build_structure_body(manifest: dict) -> str:
    areas = table(
        ["Area", "Purpose", "Rule"],
        ((area["title"], area["description"], area["rule"]) for area in manifest["areas"]),
    )
    directories = table(
        ["Path", "Area", "Role", "Codex Edit", "Release"],
        (
            (
                f"`{entry['path']}`",
                entry["area"],
                entry["role"],
                entry["codex_edit"],
                entry["release"],
            )
            for entry in manifest["directories"]
        ),
    )
    closeout = bullet_list(f"`{item}`" if item.startswith("Run ") else item for item in manifest["codex_closeout"])
    forbidden = bullet_list(f"`{pattern}`" for pattern in manifest["forbidden_release_patterns"])
    watch_paths = bullet_list(f"`{path}`" for path in manifest.get("watch_paths", []))
    watch_globs = bullet_list(f"`{pattern}`" for pattern in manifest.get("watch_path_globs", []))
    forbidden_local = bullet_list(f"`{path}`" for path in manifest.get("forbidden_local_state_paths", []))
    return "\n\n".join(
        [
            "Source of truth: `config/project-structure.manifest.json`.",
            "Development source is the only editable truth. Package output is regenerated from source and manifests.",
            "## Areas",
            areas,
            "## Directory Matrix",
            directories,
            "## Release Forbidden Patterns",
            forbidden,
            "## Self-Documentation Watch Paths",
            watch_paths,
            "## Self-Documentation Watch Globs",
            watch_globs or "- None.",
            "## Forbidden Local-State Paths",
            forbidden_local or "- None.",
            "## Codex Closeout",
            closeout,
        ]
    )


def build_ai_guide_body(manifest: dict) -> str:
    closeout = "\n".join(f"{idx}. {item}" for idx, item in enumerate(manifest["codex_closeout"], start=1))
    return "\n".join(
        [
            "Codex must treat `AGENTS.md` as the short auto-loaded guard and this file as the expanded working guide.",
            "",
            "Before changing directory layout, path rules, package manifests, installer entrypoints, profile templates, runtime boundaries, or generated package content, update `config/project-structure.manifest.json` first.",
            "",
            "Generated package output is one-way only: source -> generated package. Never patch package output and sync it back into source.",
            "",
            "Project documentation uses `docs/` as the single entrance. Regenerate `docs/文档索引.md`/`docs/doc-index.json` with `scripts/generate_docs_index.py` after stable documentation changes, and regenerate `docs/过程文档索引.md`/`docs/process-doc-index.json` with `scripts/generate_process_docs_index.py` after historical or process documentation changes.",
            "",
            "Script lifecycle governance is generated by `scripts/generate_script_lifecycle_inventory.py`; move low-risk scripts only in small batches with old-path wrappers, and do not physically move gate/hook scripts before dual-track wrapper validation.",
            "",
            "`scripts/check_doc_drift.py` verifies generated docs, package boundaries, watch-path coverage, and forbidden local-state paths. If it fails, update the manifest/source relationship or move private state back under `local/` before closing the task.",
            "",
            "Required closeout:",
            "",
            closeout,
        ]
    )


def build_runtime_body(manifest: dict) -> str:
    forbidden = bullet_list(f"`{pattern}`" for pattern in manifest["forbidden_release_patterns"] if pattern.startswith("runtime") or pattern in {"**/*.log"})
    return "\n".join(
        [
            "This directory is local runtime state, not product source.",
            "",
            "Allowed in Git/release: README files and explicit placeholder files only.",
            "",
            "Forbidden from Git/release:",
            "",
            forbidden or "- Runtime logs, reports, SQLite databases, browser profiles, cookies, and raw media.",
        ]
    )


def build_archive_body(manifest: dict) -> str:
    return "\n".join(
        [
            "This area is for sanitized historical records and user-confirmed migration evidence.",
            "",
            "Do not archive raw profiles, cookies, secrets, raw logs, browser caches, or host-local databases.",
            "",
            "Raw profile migration backups belong under `local/backups/profile-archives/`, not `archive/local/`.",
            "",
            "If an old file is needed for future work, sanitize it first and add an index note explaining provenance and risk.",
        ]
    )


def build_release_body(manifest: dict) -> str:
    return "\n".join(
        [
            "This directory is reserved for generated release staging output.",
            "",
            "Do not edit files here directly. Change source files, `config/package-manifest.product-lite.json`, or generation scripts, then rebuild.",
            "",
            "Each generated package should carry provenance such as source commit/worktree summary, manifest hash, build script hash, and file hashes.",
        ]
    )


def build_local_body(kind: str) -> str:
    if kind == "browser_data":
        return "\n".join(
            [
                "This directory stores local browser automation and session data.",
                "",
                "It may contain platform login state or anti-bot-sensitive artifacts. Keep it out of Git and release packages.",
            ]
        )
    return "\n".join(
        [
            "This directory is for machine-local user configuration, profiles, and migration scratch files.",
            "",
            "Raw profile migration backups should live under `local/backups/profile-archives/` so they remain outside release and sanitized archive paths.",
            "",
            "Keep it out of Git and release packages. Use `.example` files under `config/` for shareable templates.",
        ]
    )


def base_content(path: str) -> str:
    headings = {
        "STRUCTURE.md": "# KnowledgeRadar Structure\n",
        "docs/AI_WORKING_GUIDE.md": "# AI Working Guide\n",
        "release/README.md": "# Release Staging\n",
        "local/README.md": "# Local State\n",
        "browser_data/README.md": "# Browser Data\n",
    }
    return headings.get(path, "")


def build_outputs(manifest: dict) -> Dict[str, Dict[str, str]]:
    return {
        "STRUCTURE.md": {"STRUCTURE-MATRIX": build_structure_body(manifest)},
        "docs/AI_WORKING_GUIDE.md": {"AI-STRUCTURE-RULES": build_ai_guide_body(manifest)},
        "runtime/README.md": {"RUNTIME-BOUNDARY": build_runtime_body(manifest)},
        "archive/INDEX.md": {"ARCHIVE-BOUNDARY": build_archive_body(manifest)},
        "release/README.md": {"RELEASE-BOUNDARY": build_release_body(manifest)},
        "local/README.md": {"LOCAL-BOUNDARY": build_local_body("local")},
        "browser_data/README.md": {"BROWSER-DATA-BOUNDARY": build_local_body("browser_data")},
    }


def render_file(relative_path: str, blocks: Dict[str, str]) -> str:
    path = ROOT / relative_path
    existing = path.read_text(encoding="utf-8") if path.exists() else base_content(relative_path)
    rendered = existing
    for block_id, body in blocks.items():
        rendered = replace_block(rendered, block_id, body)
    return rendered


def apply_outputs(check: bool = False) -> List[str]:
    manifest = load_manifest()
    changed: List[str] = []
    for relative_path, blocks in build_outputs(manifest).items():
        path = ROOT / relative_path
        rendered = render_file(relative_path, blocks)
        existing = path.read_text(encoding="utf-8") if path.exists() else ""
        if rendered != existing:
            changed.append(relative_path)
            if not check:
                path.parent.mkdir(parents=True, exist_ok=True)
                path.write_text(rendered, encoding="utf-8")
    return changed


def main() -> int:
    parser = argparse.ArgumentParser(description="Generate KnowledgeRadar structure documentation.")
    parser.add_argument("--check", action="store_true", help="Exit non-zero if generated docs are stale.")
    args = parser.parse_args()
    changed = apply_outputs(check=args.check)
    if changed:
        prefix = "Stale" if args.check else "Updated"
        for item in changed:
            print(f"{prefix}: {item}")
        return 1 if args.check else 0
    print("Structure documentation is up to date.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
