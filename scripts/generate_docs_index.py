from __future__ import annotations

import argparse
from datetime import datetime, timezone
import json
from pathlib import Path
import re
import subprocess
from typing import Any


ROOT = Path(__file__).resolve().parents[1]
DOCS = ROOT / "docs"
INDEX_MD = DOCS / "文档索引.md"
INDEX_JSON = DOCS / "doc-index.json"
SCHEMA = "knowledgeradar-doc-index/v1"
GENERATED = "This file is generated by scripts/generate_docs_index.py."

EXCLUDED_DIRS = {"research", "verification", "__pycache__"}
EXCLUDED_FILES = {"文档索引.md", "脚本生命周期清单.md", "过程文档索引.md"}
TITLE_RE = re.compile(r"^#\s+(.+?)\s*$", re.MULTILINE)
FRONT_MATTER_RE = re.compile(r"\A---\s*\n(.*?)\n---\s*\n", re.DOTALL)


def _rel(path: Path) -> str:
    return path.relative_to(ROOT).as_posix()


def _git_check(path: Path, *args: str) -> bool:
    proc = subprocess.run(
        ["git", *args, "--", _rel(path)],
        cwd=ROOT,
        stdout=subprocess.DEVNULL,
        stderr=subprocess.DEVNULL,
        timeout=10,
        check=False,
    )
    return proc.returncode == 0


def _is_git_tracked(path: Path) -> bool:
    return _git_check(path, "ls-files", "--error-unmatch")


def _is_git_ignored(path: Path) -> bool:
    return _git_check(path, "check-ignore", "-q")


def _is_untracked_ignored_process_doc(path: Path) -> bool:
    return _is_git_ignored(path) and not _is_git_tracked(path)


def _read_text(path: Path) -> str:
    return path.read_text(encoding="utf-8-sig", errors="replace")


def _parse_front_matter(text: str) -> dict[str, str]:
    match = FRONT_MATTER_RE.match(text)
    if not match:
        return {}
    result: dict[str, str] = {}
    for raw_line in match.group(1).splitlines():
        if ":" not in raw_line:
            continue
        key, value = raw_line.split(":", 1)
        result[key.strip()] = value.strip().strip("\"'")
    return result


def _title(path: Path, text: str, meta: dict[str, str]) -> str:
    if meta.get("title"):
        return meta["title"]
    match = TITLE_RE.search(text)
    if match:
        return match.group(1).strip()
    return path.stem


def _doc_type(path: Path, meta: dict[str, str]) -> str:
    if meta.get("doc_type"):
        return meta["doc_type"]
    parts = path.relative_to(DOCS).parts
    if len(parts) > 1:
        folder = parts[0]
        if folder in {"reference", "design", "research", "verification"}:
            return folder
    return "docs"


def _status(path: Path, meta: dict[str, str]) -> str:
    if meta.get("status"):
        return meta["status"]
    normalized = path.as_posix()
    if "/research/" in normalized or "/verification/" in normalized:
        return "draft"
    if path.name in {"文档索引.md"}:
        return "generated"
    return "current"


def _evidence_path(path: Path, meta: dict[str, str]) -> str:
    if meta.get("evidence"):
        return meta["evidence"]
    candidate = path.with_suffix(".evidence.json")
    return _rel(candidate) if candidate.exists() else ""


def discover_docs() -> list[dict[str, Any]]:
    items: list[dict[str, Any]] = []
    for path in sorted(DOCS.rglob("*.md")):
        if path.name in EXCLUDED_FILES:
            continue
        if _is_untracked_ignored_process_doc(path):
            continue
        rel_parts = path.relative_to(DOCS).parts
        if rel_parts and rel_parts[0] in EXCLUDED_DIRS:
            # Keep draft/process areas out of the current stable index by default.
            continue
        text = _read_text(path)
        meta = _parse_front_matter(text)
        evidence = _evidence_path(path, meta)
        items.append(
            {
                "path": _rel(path),
                "title": _title(path, text, meta),
                "doc_type": _doc_type(path, meta),
                "status": _status(path, meta),
                "scope": meta.get("scope", "KnowledgeRadar"),
                "evidence": evidence,
                "has_evidence": bool(evidence and (ROOT / evidence).exists()),
                "updated_at": meta.get("updated_at", ""),
            }
        )
    return items


def _group_items(items: list[dict[str, Any]]) -> dict[str, list[dict[str, Any]]]:
    groups: dict[str, list[dict[str, Any]]] = {}
    for item in items:
        groups.setdefault(str(item["doc_type"]), []).append(item)
    return dict(sorted(groups.items()))


def render_markdown(payload: dict[str, Any]) -> str:
    lines = [
        "# 文档索引",
        "",
        GENERATED,
        "",
        f"生成时间：{payload['generated_at']}",
        "",
        "## 使用规则",
        "",
        "- `docs/` 是当前 KnowledgeRadar 项目的统一文档入口。",
        "- `reference` 表示长期规则和稳定治理材料；`design` 表示当前设计；草稿和一次性验收材料不默认进入稳定索引。",
        "- 稳定研究/治理文档应有同名 `.evidence.json`，供后续 Agent 和质量检查读取。",
        "- 如果 Knowledge Reader 在其他项目中工作，应遵守目标项目自己的文档规则。",
        "",
    ]
    for group, docs in _group_items(payload["documents"]).items():
        lines.extend([f"## {group}", "", "| 标题 | 路径 | 状态 | 证据 |", "| --- | --- | --- | --- |"])
        for item in docs:
            evidence = item["evidence"] or "-"
            lines.append(f"| {item['title']} | `{item['path']}` | {item['status']} | `{evidence}` |")
        lines.append("")
    return "\n".join(lines).rstrip() + "\n"


def build_index() -> dict[str, Any]:
    documents = discover_docs()
    mtimes = [
        (ROOT / item["path"]).stat().st_mtime
        for item in documents
        if (ROOT / item["path"]).exists()
    ]
    generated_at = datetime.fromtimestamp(max(mtimes) if mtimes else 0, timezone.utc).isoformat()
    return {
        "schema": SCHEMA,
        "generated_at": generated_at,
        "generator": "scripts/generate_docs_index.py",
        "documents": documents,
    }


def write_outputs(payload: dict[str, Any], *, check: bool) -> list[str]:
    INDEX_MD.parent.mkdir(parents=True, exist_ok=True)
    outputs = {
        INDEX_MD: render_markdown(payload),
        INDEX_JSON: json.dumps(payload, ensure_ascii=False, indent=2) + "\n",
    }
    changed: list[str] = []
    for path, text in outputs.items():
        existing = path.read_text(encoding="utf-8") if path.exists() else ""
        if existing != text:
            changed.append(_rel(path))
            if not check:
                path.write_text(text, encoding="utf-8")
    return changed


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    parser.add_argument("--json", action="store_true")
    args = parser.parse_args(argv)

    payload = build_index()
    changed = write_outputs(payload, check=args.check)
    result = {
        "schema": "knowledgeradar-doc-index-generation/v1",
        "status": "PASS" if not changed else ("FAIL" if args.check else "PASS"),
        "changed": changed,
        "document_count": len(payload["documents"]),
    }
    if args.json:
        print(json.dumps(result, ensure_ascii=False, indent=2))
    else:
        if changed:
            print("Doc index differs:" if args.check else "Doc index updated:")
            for item in changed:
                print(f"- {item}")
        else:
            print("Doc index is up to date.")
    return 0 if result["status"] == "PASS" else 1


if __name__ == "__main__":
    raise SystemExit(main())
