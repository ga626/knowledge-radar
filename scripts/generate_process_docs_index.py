from __future__ import annotations

import argparse
from datetime import datetime, timezone
import json
from pathlib import Path
import re
from typing import Any


ROOT = Path(__file__).resolve().parents[1]
OUTPUT_JSON = ROOT / "docs" / "process-doc-index.json"
OUTPUT_MD = ROOT / "docs" / "过程文档索引.md"
SCHEMA = "knowledgeradar-process-doc-index/v1"
GENERATED = "This file is generated by scripts/generate_process_docs_index.py."
TITLE_RE = re.compile(r"^#\s+(.+?)\s*$", re.MULTILINE)


SOURCES = [
    ("design_docs", ROOT / "design_docs", "legacy_process_docs"),
    ("archive_history", ROOT / "archive" / "history", "historical_evidence"),
    ("docs_research", ROOT / "docs" / "research", "draft_research"),
    ("docs_verification", ROOT / "docs" / "verification", "verification_record"),
]


def _rel(path: Path) -> str:
    return path.relative_to(ROOT).as_posix()


def _read_head(path: Path, limit: int = 12000) -> str:
    try:
        return path.read_text(encoding="utf-8-sig", errors="replace")[:limit]
    except OSError:
        return ""


def _title(path: Path, text: str) -> str:
    match = TITLE_RE.search(text)
    if match:
        return match.group(1).strip()
    return path.stem


def _doc_kind(path: Path) -> str:
    name = path.name
    if name.startswith("设计_"):
        return "设计"
    if name.startswith("执行_"):
        return "执行"
    if name.startswith("产品化_"):
        return "产品化"
    if name.startswith("方法论_"):
        return "方法论"
    return "过程"


def _status(source_id: str, path: Path) -> str:
    if source_id == "docs_verification":
        return "验收记录"
    if source_id == "docs_research":
        return "草稿调研"
    if "ArchiveIndex" in path.name or path.name.upper() == "INDEX.MD":
        return "历史索引"
    return "历史证据"


def discover_process_docs() -> list[dict[str, Any]]:
    items: list[dict[str, Any]] = []
    for source_id, root, source_type in SOURCES:
        if not root.exists():
            continue
        for path in sorted(root.rglob("*.md")):
            text = _read_head(path)
            stat = path.stat()
            items.append(
                {
                    "path": _rel(path),
                    "title": _title(path, text),
                    "source": source_id,
                    "source_type": source_type,
                    "doc_kind": _doc_kind(path),
                    "status": _status(source_id, path),
                    "size_bytes": stat.st_size,
                    "mtime_utc": datetime.fromtimestamp(stat.st_mtime, timezone.utc).isoformat(),
                    "promotion_rule": "Only promote to docs/reference or docs/design after owner review and evidence-sidecar update.",
                }
            )
    return items


def build_index() -> dict[str, Any]:
    documents = discover_process_docs()
    mtimes = [
        (ROOT / item["path"]).stat().st_mtime
        for item in documents
        if (ROOT / item["path"]).exists()
    ]
    generated_at = datetime.fromtimestamp(max(mtimes) if mtimes else 0, timezone.utc).isoformat()
    return {
        "schema": SCHEMA,
        "generated_at": generated_at,
        "generator": "scripts/generate_process_docs_index.py",
        "document_count": len(documents),
        "sources": [
            {"id": source_id, "path": _rel(root), "source_type": source_type}
            for source_id, root, source_type in SOURCES
            if root.exists()
        ],
        "documents": documents,
    }


def _counts(items: list[dict[str, Any]], key: str) -> dict[str, int]:
    result: dict[str, int] = {}
    for item in items:
        value = str(item.get(key) or "")
        result[value] = result.get(value, 0) + 1
    return dict(sorted(result.items()))


def render_markdown(payload: dict[str, Any]) -> str:
    docs = payload["documents"]
    lines = [
        "# 过程文档索引",
        "",
        GENERATED,
        "",
        f"生成时间：{payload['generated_at']}",
        f"记录数量：{payload['document_count']}",
        "",
        "## 使用规则",
        "",
        "- 这是 `docs/` 统一入口下的历史/过程文档目录，不表示这些文档当前有效。",
        "- `design_docs/`、`archive/history/`、`docs/research/`、`docs/verification/` 中的材料默认是历史证据、草稿或验收记录。",
        "- 需要升级为当前规则或设计时，应迁入 `docs/reference/` 或 `docs/design/`，并补同名 evidence sidecar。",
        "- Agent 查找历史线索时先读本索引，再按需打开具体文件；不要把历史结论直接当当前事实。",
        "",
        "## 统计",
        "",
        "| 维度 | 数量 |",
        "| --- | ---: |",
    ]
    for status, count in _counts(docs, "status").items():
        lines.append(f"| {status} | {count} |")
    lines.extend(["", "## 来源", "", "| 来源 | 类型 | 数量 |", "| --- | --- | ---: |"])
    source_counts = _counts(docs, "source")
    for source in payload["sources"]:
        lines.append(f"| `{source['path']}` | {source['source_type']} | {source_counts.get(source['id'], 0)} |")
    lines.extend(["", "## 文件清单", "", "| 标题 | 路径 | 状态 | 类型 |", "| --- | --- | --- | --- |"])
    for item in docs:
        lines.append(f"| {item['title']} | `{item['path']}` | {item['status']} | {item['doc_kind']} |")
    return "\n".join(lines).rstrip() + "\n"


def write_outputs(payload: dict[str, Any], *, check: bool) -> list[str]:
    outputs = {
        OUTPUT_JSON: json.dumps(payload, ensure_ascii=False, indent=2) + "\n",
        OUTPUT_MD: render_markdown(payload),
    }
    changed: list[str] = []
    for path, text in outputs.items():
        existing = path.read_text(encoding="utf-8") if path.exists() else ""
        if existing != text:
            changed.append(_rel(path))
            if not check:
                path.parent.mkdir(parents=True, exist_ok=True)
                path.write_text(text, encoding="utf-8")
    return changed


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    parser.add_argument("--json", action="store_true")
    args = parser.parse_args(argv)

    payload = build_index()
    changed = write_outputs(payload, check=args.check)
    result = {
        "schema": "knowledgeradar-process-doc-index-generation/v1",
        "status": "PASS" if not changed else ("FAIL" if args.check else "PASS"),
        "changed": changed,
        "document_count": payload["document_count"],
    }
    if args.json:
        print(json.dumps(result, ensure_ascii=False, indent=2))
    else:
        if changed:
            print("Process doc index differs:" if args.check else "Process doc index updated:")
            for item in changed:
                print(f"- {item}")
        else:
            print("Process doc index is up to date.")
    return 0 if result["status"] == "PASS" else 1


if __name__ == "__main__":
    raise SystemExit(main())
