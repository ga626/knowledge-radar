def source_ecology_manifest():
    return deepcopy(_DECLARATION)


def candidate_tools(ecology_id):
    return source_ecology_manifest()['ecologies'].get(ecology_id, {}).get('candidate_tools', [])


def ecology_for_platform(platform):
    value = str(platform).casefold()
    return next((key for key, item in _DECLARATION['ecologies'].items()
                 if value in {name.casefold() for name in item['platform_aliases']}), 'unmapped')


def joined_catalog(registry):
    """合并已注册平台，不把注册/启用等同账号可用或真实验过。"""
    from dataclasses import asdict
    from runtime.recruitment_sources import recruitment_source_capability
    result = source_ecology_manifest()
    result['registered_platforms'] = {}
    for platform in registry.platforms():
        adapter = registry.get(platform)
        item = {'ecology_id': ecology_for_platform(platform),
                'declared': asdict(adapter.capabilities), 'ready': 'not_probed', 'verified': False}
        source = recruitment_source_capability(platform)
        if item['ecology_id'] == 'career_recruitment_ecology':
            item['source_contract'] = source.to_dict()
        result['registered_platforms'][platform] = item
    return result
